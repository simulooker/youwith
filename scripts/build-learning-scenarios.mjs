import {annotateLearning} from './learning-notes.mjs';
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {XORNetwork,XOR_DATA} from '../frontend/tech/neural-math.js';
import {FRUIT_DATA,buildTree,predictTree} from '../frontend/tech/decision-tree-math.js';

// Run during authoring only. Browsers import the saved arrays, never these solvers.
export function buildScenarios(){
  const network=new XORNetwork(),snapshots=[];
  for(const epoch of [0,1,200,4000]){
    if(epoch>network.epochs)network.train(epoch-network.epochs,.5);
    snapshots.push({epochs:network.epochs,loss:network.loss(),w1:structuredClone(network.w1),b1:[...network.b1],w2:[...network.w2],b2:network.b2,gradients:network.gradients(),outputs:XOR_DATA.map(({x,y})=>({x,y,...network.forward(x)}))});
  }
  const stages=[
    {title:'입력을 넣어요',description:'XOR은 두 입력이 다르면 1, 같으면 0입니다. 아직 학습하지 않은 네트워크에 선택한 입력을 넣습니다.',snapshot:0,phase:0},
    {title:'은닉층을 지나가요',description:'입력 × 가중치에 편향을 더하고 tanh를 통과한 네 개의 값을 보여줍니다.',snapshot:0,phase:1},
    {title:'처음 예측을 봐요',description:'출력층의 sigmoid 값은 1을 예측하는 확률입니다. 50% 이상이면 1로 판정합니다.',snapshot:0,phase:2},
    {title:'정답과 비교해요',description:'선택한 입력의 정답을 비교합니다. 평균 손실은 XOR 네 표본 전체의 BCE입니다.',snapshot:0,phase:3},
    {title:'오차를 거꾸로 전달해요',description:'역전파로 평균 손실에 대한 각 가중치·편향의 기울기를 구합니다. 아래 설정 보기에 저장된 기울기를 확인할 수 있어요.',snapshot:0,phase:4},
    {title:'한 번 조정해요',description:'학습률 0.5로 가중치에서 기울기 × 학습률을 뺀 1회 학습 결과입니다.',snapshot:1,phase:5},
    {title:'반복해서 배워요',description:'네 표본을 200회 반복한 결과입니다. 연결의 굵기와 예측, 손실이 함께 달라집니다.',snapshot:2,phase:5},
    {title:'학습 결과를 확인해요',description:'4,000회 학습한 결과입니다. 아래 표에서 선택한 입력뿐 아니라 네 입력 모두의 예측을 확인하세요.',snapshot:3,phase:5}
  ];
  const trees=[0,1,2].map(depth=>{
    const tree=buildTree(FRUIT_DATA,depth),result=predictTree(tree,[170,6.4]);
    function residual(n){return n.feature===null?n.count*n.impurity:residual(n.left)+residual(n.right);}
    return {depth,tree,result,impurity:residual(tree)/tree.count,correct:FRUIT_DATA.filter(row=>predictTree(tree,row.x).prediction===row.y).length};
  });
  const common=[
    {title:'같은 표본을 준비해요',description:'질량 170 g, 지름 6.4 cm인 가상 사과를 분류합니다. 학습 표본은 아래의 가상 과일 10개입니다.',snapshot:0,pathLength:0},
    {title:'첫 질문을 골라요',description:'두 특성의 중간값 후보를 비교한 결과, 질량 155 g을 기준으로 나누면 가중 지니 불순도가 가장 많이 줄어듭니다.',snapshot:0,pathLength:1},
    {title:'질량으로 한 번 나눠요',description:'155 g 이하와 초과로 나눴습니다. 오른쪽에는 사과 1개와 오렌지 5개가 섞여 있습니다.',snapshot:1,pathLength:1},
    {title:'170 g의 길을 따라가요',description:'170 g은 155 g보다 크므로 오른쪽으로 갑니다. 여기서 멈추면 다수인 오렌지를 예측해 이 사과를 틀립니다.',snapshot:1,pathLength:2}
  ];
  return annotateLearning({
    version:2,network:{architecture:[2,4,1],rate:.5,data:XOR_DATA,snapshots,stages,cases:[{title:'경우 1',subtitle:'입력이 서로 다를 때',sample:1},{title:'경우 2',subtitle:'입력이 서로 같을 때',sample:3}]},
    tree:{data:FRUIT_DATA,input:[170,6.4],target:0,snapshots:trees,cases:[
      {title:'경우 1',subtitle:'한 번만 나누기',stages:[...common,{title:'얕은 트리의 결과',description:'학습 표본 10개 중 9개를 맞췄지만 이 표본은 오렌지로 잘못 분류합니다. 한 질문만으로는 구분이 부족합니다.',snapshot:1,pathLength:2}]},
      {title:'경우 2',subtitle:'질문을 하나 더 하기',stages:[...common,{title:'지름을 한 번 더 물어요',description:'오른쪽 표본을 지름 6.65 cm 이하와 초과로 다시 나눕니다. 질량이 비슷해도 지름이 작은 사과를 구분할 수 있습니다.',snapshot:2,pathLength:2},{title:'작은 지름의 길로 가요',description:'6.4 cm는 6.65 cm 이하이므로 왼쪽 잎으로 갑니다. 이 잎에는 가상 사과 1개가 있습니다.',snapshot:2,pathLength:3},{title:'사과를 올바르게 분류해요',description:'학습 표본 10개를 모두 맞췄습니다. 이 수치는 학습 데이터에서의 결과이며, 새로운 과일에 대한 성능을 보장하지 않습니다.',snapshot:2,pathLength:3}]}
    ]}
  });
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
  const target=new URL('../frontend/tech/learning-scenarios.js',import.meta.url);
  await writeFile(target,'// Generated by npm run tech:build-scenarios. Do not edit numeric results by hand.\nexport const SCENARIOS='+JSON.stringify(buildScenarios())+';\n');
  console.log('Saved XOR forward/backprop/training and CART scenarios. No browser training required.');
}
