import {writeFile} from 'node:fs/promises';
import {SIGNALS} from '../frontend/tech/signal-scenarios.js';
import {TAU,integral,pulseTransform,dtft} from '../frontend/tech/signal-math.js';

const result=SIGNALS.map(d=>{
 let parts;
 if(d.id==='fs'||d.id==='dtfs'){
  const discrete=d.id==='dtfs',angle=x=>discrete?TAU*x/8:x;
  parts=[{label:discrete?'k=1,7 · 기본 주파수':'ω=1 rad/s · 기본 주파수',short:discrete?'cos(2πn/8)':'cos(t)',kind:'cos',harmonic:1,amplitude:1,note:discrete?'c₁=c₇=0.5입니다. k=7은 한 주기 안에서 k=−1과 같은 파동입니다.':'c₁=c₋₁=0.5입니다. 양·음 주파수 한 쌍을 더하면 진폭 1의 cos(t)가 됩니다.',values:d.time.map(t=>Math.cos(angle(t)))},
   {label:discrete?'k=2,6 · 두 배 주파수':'ω=2 rad/s · 두 배 주파수',short:discrete?'0.5 sin(4πn/8)':'0.5 sin(2t)',kind:'sin',harmonic:2,amplitude:.5,note:discrete?'c₂=−0.25j, c₆=+0.25j입니다. 켤레인 두 성분이 합쳐져 실수 사인파가 됩니다.':'c₂=−0.25j, c₋₂=+0.25j입니다. 두 성분이 합쳐져 진폭 0.5의 sin(2t)가 됩니다.',values:d.time.map(t=>.5*Math.sin(2*angle(t)))}];
 }else{
  const limit=d.id==='ft'?6*Math.PI:Math.PI;
  parts=Array.from({length:4},(_,i)=>{
   const low=limit*i/4,high=limit*(i+1)/4;
   const term=t=>integral(w=>{const z=d.id==='ft'?pulseTransform(w):dtft([1,1,1],w);return z.re*Math.cos(w*t)-z.im*Math.sin(w*t);},low,high,150)/Math.PI;
   return {label:`대역 ${i+1} · ${(low/Math.PI).toFixed(2)}π…${(high/Math.PI).toFixed(2)}π`,short:`대역 ${i+1}`,kind:'band',low,high,note:'한 주파수의 순수 정현파가 아니라 연속된 주파수 묶음의 기여입니다. 실수 신호의 양·음 주파수 쌍을 묶어 표시합니다.',values:d.time.map(term)};
  });
 }
 const sum=d.time.map((_,i)=>parts.reduce((total,p)=>total+p.values[i],0));
 const probe=d.id==='fs'?Math.PI/4:d.id==='ft'?.25:1;
 const index=d.time.reduce((best,t,i)=>Math.abs(t-probe)<Math.abs(d.time[best]-probe)?i:best,0);
 return {id:d.id,title:d.title,type:d.type,discrete:d.discrete,time:d.time,input:d.input,sourceFormula:d.formula,parts,sum,exact:d.id!=='ft',error:Math.max(...sum.map((y,i)=>Math.abs(y-d.input[i]))),probe:{index,label:d.id==='fs'?'t=π/4':d.id==='ft'?'t=0.25':'n=1',values:parts.map(p=>p.values[index]),sum:sum[index],input:d.input[index]}};
});
await writeFile(new URL('../frontend/tech/signal-components.js',import.meta.url),'// Generated by npm run tech:build-signals.\nexport const COMPONENTS='+JSON.stringify(result)+';\n');
console.log('Saved real harmonic pairs and complementary frequency-band contributions.');
