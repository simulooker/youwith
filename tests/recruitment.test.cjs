const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(__dirname + '/../frontend/recruitment.js','utf8');
const saved = new Map();
const storage = {getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v)};
function open(localStorage=storage) {
 const context=vm.createContext({localStorage,projects:[{title:'Seed',desc:'Role',skills:[],detail:'Detail',icon:'code',type:'팀원 모집'}]});
 vm.runInContext(source,context);
 return context;
}
const first=open();
assert.throws(()=>vm.runInContext(`createRecruitment({title:' ',roles:'Developer'})`,first),/프로젝트 이름/);
vm.runInContext(`createRecruitment({title:'Owner project',roles:'Backend',detail:'My details',skills:'Python, SQL'})`,first);
assert.equal(vm.runInContext('ownedProjects().length',first),1);
const ownerId=vm.runInContext('ownedProjects()[0].id',first);
assert.throws(()=>vm.runInContext(`submitRecruitmentApplication(${JSON.stringify(ownerId)},{})`,first),/다른 부원/);
vm.runInContext(`submitRecruitmentApplication('sample-project-0',{name:'지원 테스트',major:'전자 3학년',skills:'Python',message:'같이 개발하고 싶어요'})`,first);
vm.runInContext(`createRecruitment({title:'Second project',roles:'Frontend'})`,first);
assert.equal(vm.runInContext(`myApplication(projects.find(p=>p.id==='sample-project-0')).status`,first),'pending');
assert.throws(()=>vm.runInContext(`submitRecruitmentApplication('sample-project-0',{name:'A',major:'B',skills:'C',message:'D'})`,first),/이미 지원/);
assert.throws(()=>vm.runInContext(`setRecruitmentStatus(recruitmentState.applications[0].id,'approved')`,first),/내 모집글/);
const second=open();
assert.equal(vm.runInContext('ownedProjects().length',second),2);
assert.equal(vm.runInContext(`myApplication(projects.find(p=>p.id==='sample-project-0')).name`,second),'지원 테스트');
vm.runInContext(`recruitmentState.applications.push({id:'incoming',projectId:ownedProjects()[0].id,memberId:'other-member',name:'검토 테스트',major:'반도체',skills:'회로',message:'설계 경험',status:'pending'});setRecruitmentStatus('incoming','approved')`,second);
assert.equal(vm.runInContext(`recruitmentState.applications.find(a=>a.id==='incoming').status`,second),'approved');
const editedId=vm.runInContext('ownedProjects()[0].id',second);
assert.throws(()=>vm.runInContext(`updateRecruitment('sample-project-0',{title:'No',roles:'No'})`,second),/내가 작성한/);
assert.throws(()=>vm.runInContext(`deleteRecruitment('sample-project-0')`,second),/내가 작성한/);
vm.runInContext(`updateRecruitment(${JSON.stringify(editedId)},{title:'Edited title',roles:'Circuit',detail:'New details',skills:'Verilog'})`,second);
assert.equal(vm.runInContext(`projects.find(p=>p.id===${JSON.stringify(editedId)}).title`,second),'Edited title');
assert.equal(vm.runInContext(`recruitmentState.applications.find(a=>a.id==='incoming').status`,second),'approved');
vm.runInContext(`deleteRecruitment(${JSON.stringify(editedId)})`,second);
assert.equal(vm.runInContext(`projects.some(p=>p.id===${JSON.stringify(editedId)})`,second),false);
assert.equal(vm.runInContext(`recruitmentState.applications.some(a=>a.id==='incoming')`,second),false);
assert.equal(vm.runInContext(`myApplication(projects.find(p=>p.id==='sample-project-0')).status`,second),'pending');
assert.equal(vm.runInContext('ownedProjects().length',open()),1);
saved.set('youwith.recruitment.v1','{bad');
assert.equal(vm.runInContext('ownedProjects().length',open()),0);
const blocked=open({getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}});
assert.equal(vm.runInContext(`createRecruitment({title:'Still usable',roles:'Developer'}).saved`,blocked),false);
assert.equal(vm.runInContext('ownedProjects().length',blocked),1);
console.log('Recruitment persistence, stable IDs, validation, owner controls and storage failure passed.');
